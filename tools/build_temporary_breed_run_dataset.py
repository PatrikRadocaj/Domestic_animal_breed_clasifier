def _stable_id(*parts: str) -> str:
    return sha1("::".join(parts).encode("utf-8")).hexdigest()[:20]


def normalize_label(text: str) -> str:
    out = re.sub(r"[^a-z0-9]+", "_", str(text).strip().lower()).strip("_")
    while "__" in out:
        out = out.replace("__", "_")
    return out


def canonical_species(raw: str) -> str:
    return SPECIES_CANONICAL.get(normalize_label(raw), normalize_label(raw))


def guess_species_from_dataset_name(name: str) -> str | None:
    norm = normalize_label(name)
    tokens = set(norm.split("_"))
    for token, species_id in SPECIES_CANONICAL.items():
        if token == "multi":
            continue
        if token in tokens:
            return species_id
    return None


def canonical_breed_slug(species_id: str, raw_label: str, dataset_id: str = "") -> str:
    dataset_key = str(dataset_id).strip()
    if dataset_key:
        resolution = LABEL_MAP.resolve_breed(species_id, raw_label, dataset_key)
        if resolution.status == "resolved" and resolution.canonical_id:
            return resolution.canonical_id.split(":", 1)[-1]

    label = normalize_label(raw_label)
    if not label:
        return "unknown"
    tokens = [tok for tok in label.split("_") if tok and tok not in NOISE_TOKENS]
    cleaned = "_".join(tokens).strip("_")
    if not cleaned:
        cleaned = label
    # Collapse common prefix/suffix duplication after token cleaning.
    cleaned = cleaned.replace("holstein_friesian_friesian", "holstein_friesian")
    cleaned = cleaned.replace("american_quarter", "quarter")
    cleaned = cleaned.replace("arabian_horse", "arabian")
    cleaned = cleaned.replace("friesian_horse", "friesian")
    if cleaned == "unknown":
        return "unknown"
    return cleaned


def _safe_image_size(path: Path) -> tuple[int, int] | None:
    try:
        with Image.open(path) as image:
            image = ImageOps.exif_transpose(image)
            return image.size
    except (UnidentifiedImageError, OSError, DecompressionBombError, SyntaxError, ValueError):
        return None


def _is_readable_image(path: Path) -> bool:
    try:
        with Image.open(path) as image:
            image = ImageOps.exif_transpose(image)
            image.load()
        return True
    except (UnidentifiedImageError, OSError, DecompressionBombError, SyntaxError, ValueError):
        return False


def _split_for_key(key: str) -> str:
    bucket = int(sha1(key.encode("utf-8")).hexdigest()[:8], 16) % 100
    if bucket < 80:
        return "train"
    if bucket < 90:
        return "val"
    return "test"


def _bbox_xywhn_to_xyxy(box: list[float], width: int, height: int) -> tuple[float, float, float, float]:
    xc, yc, wn, hn = [float(v) for v in box]
    bw = wn * width
    bh = hn * height
    xmin = max(0.0, (xc * width) - (bw / 2.0))
    ymin = max(0.0, (yc * height) - (bh / 2.0))
    xmax = min(float(width), xmin + bw)
    ymax = min(float(height), ymin + bh)
    return xmin, ymin, xmax, ymax


@dataclass
class RegistryEntry:
    dataset_id: str
    source_type: str
    expected_format: str
    species_value: str
    license: str
    notes: str


@dataclass
class ManifestRow:
    image_id: str
    path: str
    source: str
    source_url: str
    source_type: str
    license: str
    species_id: str
    breed_id: str
    raw_label: str
    bbox_source: str
    width: int
    height: int
    bbox_xmin: float
    bbox_ymin: float
    bbox_xmax: float
    bbox_ymax: float
    is_crowd: bool
    split_group: str
    duplicate_cluster: str
    quality_tags: str
    split: str


def load_registry() -> dict[str, RegistryEntry]:
    entries: dict[str, RegistryEntry] = {}
    with REGISTRY_PATH.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            dataset_id = str(row.get("dataset_id", "")).strip()
            if not dataset_id:
                continue
            entries[dataset_id] = RegistryEntry(
                dataset_id=dataset_id,
                source_type=str(row.get("source_type", "")).strip(),
                expected_format=str(row.get("expected_format", "")).strip(),
                species_value=canonical_species(str(row.get("species_value", "")).strip()),
                license=str(row.get("license", "unknown")).strip() or "unknown",
                notes=str(row.get("notes", "")).strip(),
            )
    return entries


def read_data_yaml(path: Path) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def iter_yolo_splits(root: Path) -> Iterable[tuple[str, Path, Path, Path | None]]:
    data = read_data_yaml(root / "data.yaml")
    split_map = {
        "train": str(data.get("train", "images/train")),
        "val": str(data.get("val", "images/val")),
        "test": str(data.get("test", "images/test")),
    }
    for split, image_rel in split_map.items():
        image_dir = (root / image_rel).resolve()
        if not image_dir.exists():
            image_dir = root / image_rel
        if not image_dir.exists() and image_rel.startswith("../"):
            image_dir = root / image_rel.removeprefix("../")
        parts = list(Path(image_rel).parts)
        if parts and parts[0] == "..":
            parts = parts[1:]
        if len(parts) >= 2 and parts[-1] == "images":
            label_dir = root / Path(*parts[:-1], "labels")
            meta_dir = root / Path(*parts[:-1], "metadata")
        elif len(parts) >= 2 and parts[0] == "images":
            label_dir = root / Path("labels", *parts[1:])
            meta_dir = root / Path("metadata", *parts[1:])
        else:
            label_dir = root / "labels" / Path(image_rel).name
            meta_dir = root / "metadata" / Path(image_rel).name
        if image_dir.exists() and label_dir.exists():
            yield split, image_dir, label_dir, meta_dir if meta_dir.exists() else None


def build_row(
    *,
    image_path: Path,
    source: str,
    source_type: str,
    license_name: str,
    species_id: str,
    breed_id: str,
    raw_label: str,
    bbox_xyxy: tuple[float, float, float, float],
    split: str,
    bbox_source: str,
) -> ManifestRow | None:
    size = _safe_image_size(image_path)
    if size is None:
        return None
    width, height = size
    xmin, ymin, xmax, ymax = bbox_xyxy
    if xmax <= xmin or ymax <= ymin:
        return None
    image_id = _stable_id(source, str(image_path.resolve()), breed_id, f"{xmin:.2f}", f"{ymin:.2f}", f"{xmax:.2f}", f"{ymax:.2f}")
    return ManifestRow(
        image_id=image_id,
        path=str(image_path.resolve()),
        source=source,
        source_url="",
        source_type=source_type,
        license=license_name,
        species_id=species_id,
        breed_id=breed_id,
        raw_label=raw_label,
        bbox_source=bbox_source,
        width=int(width),
        height=int(height),
        bbox_xmin=float(xmin),
        bbox_ymin=float(ymin),
        bbox_xmax=float(xmax),
        bbox_ymax=float(ymax),
        is_crowd=False,
        split_group=image_id,
        duplicate_cluster=image_id,
        quality_tags="temporary_breed_run",
        split=split,
    )


def extract_rows_from_sidecar(meta_path: Path, dataset_root_name: str, registry: dict[str, RegistryEntry]) -> list[ManifestRow]:
    payload = json.loads(meta_path.read_text(encoding="utf-8"))
    source_dataset = str(payload.get("source_dataset_id") or dataset_root_name).strip()
    reg = registry.get(source_dataset)
    source_type = reg.source_type if reg else "yolo"
    license_name = reg.license if reg else "unknown"
    image_path = Path(str(payload["image_path"]))
    split = str(payload.get("split", "train")).replace("valid", "val")
    size = _safe_image_size(image_path)
    if size is None:
        return []
    width, height = size

    rows: list[ManifestRow] = []
    for obj in payload.get("objects", []):
        species_id = canonical_species(str(obj.get("species_name") or obj.get("class_name") or ""))
        raw_breed = str(obj.get("source_label_name") or obj.get("subspecies") or "").strip()
        subspecies = normalize_label(str(obj.get("subspecies", "")))
        if not raw_breed or subspecies == "unknown":
            continue
        breed_slug = canonical_breed_slug(species_id, raw_breed, source_dataset)
        if breed_slug == "unknown":
            continue
        breed_id = f"{species_id}:{breed_slug}"
        bbox = _bbox_xywhn_to_xyxy(list(obj["bbox_xywhn"]), width, height)
        row = build_row(
            image_path=image_path,
            source=source_dataset,
            source_type=source_type,
            license_name=license_name,
            species_id=species_id,
            breed_id=breed_id,
            raw_label=raw_breed,
            bbox_xyxy=bbox,
            split=split,
            bbox_source="existing_yolo",
        )
        if row is not None:
            rows.append(row)
    return rows


def extract_rows_from_plain_yolo(
    *,
    dataset_root: Path,
    species_id: str,
    source_name: str,
    source_type: str,
    license_name: str,
    progress_prefix: str | None = None,
) -> list[ManifestRow]:
    data = read_data_yaml(dataset_root / "data.yaml")
    class_names = list(data.get("names", []))
    if not class_names:
        return []
    rows: list[ManifestRow] = []
    for split, image_dir, label_dir, _ in iter_yolo_splits(dataset_root):
        out_split = split.replace("valid", "val")
        image_index: dict[str, Path | None] = {}
        for image_path in image_dir.iterdir():
            if not image_path.is_file() or image_path.suffix.lower() not in VALID_IMAGE_EXTS:
                continue
            stem = image_path.stem
            if stem in image_index:
                image_index[stem] = None
            else:
                image_index[stem] = image_path
        label_paths = sorted(label_dir.glob("*.txt"))
        total_labels = len(label_paths)
        for label_index, label_path in enumerate(label_paths, start=1):
            image_path = image_index.get(label_path.stem)
            if image_path is None:
                continue
            size = _safe_image_size(image_path)
            if size is None:
                continue
            width, height = size
            for raw in label_path.read_text(encoding="utf-8", errors="ignore").splitlines():
                parts = raw.strip().split()
                if len(parts) != 5:
                    continue
                class_idx = int(float(parts[0]))
                if class_idx < 0 or class_idx >= len(class_names):
                    continue
                raw_breed = str(class_names[class_idx])
                breed_slug = canonical_breed_slug(species_id, raw_breed, source_name)
                if breed_slug == "unknown":
                    continue
                bbox = _bbox_xywhn_to_xyxy([float(parts[1]), float(parts[2]), float(parts[3]), float(parts[4])], width, height)
                row = build_row(
                    image_path=image_path,
                    source=source_name,
                    source_type=source_type,
                    license_name=license_name,
                    species_id=species_id,
                    breed_id=f"{species_id}:{breed_slug}",
                    raw_label=raw_breed,
                    bbox_xyxy=bbox,
                    split=out_split,
                    bbox_source="existing_yolo",
                )
                if row is not None:
                    rows.append(row)
            if progress_prefix and (label_index % 1000 == 0 or label_index == total_labels):
                log_progress(
                    f"{progress_prefix} split={out_split} labels_processed={label_index}/{total_labels} rows={len(rows)}"
                )
    return rows


def locate_dataset_root(entry: RegistryEntry) -> Path | None:
    candidates = [
        NON_YOLO_ROOT / entry.dataset_id,
        YOLO_SOURCES_ROOT / entry.dataset_id,
    ]
    if entry.dataset_id.endswith("-wikimedia"):
        species_key = entry.dataset_id.replace("-breeds-wikimedia", "").replace("-wikimedia", "")
        candidates.append(NON_YOLO_ROOT / "wikimedia" / species_key)
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return None


def iter_raw_breed_images(root: Path) -> Iterable[tuple[Path, str]]:
    for image_path in root.rglob("*"):
        if not image_path.is_file() or image_path.suffix.lower() not in VALID_IMAGE_EXTS:
            continue
        ancestors = list(image_path.relative_to(root).parts[:-1])
        if not ancestors:
            continue
        breed_label = ""
        for part in reversed(ancestors):
            norm = normalize_label(part)
            if norm in SPLIT_WRAPPERS or not norm:
                continue
            breed_label = part
            break
        if breed_label:
            yield image_path, breed_label


def collect_yolo_breed_rows(registry: dict[str, RegistryEntry]) -> tuple[list[ManifestRow], set[str]]:
    return collect_yolo_breed_rows_filtered(registry, start_index=1, end_index=None)


def collect_yolo_breed_rows_filtered(
    registry: dict[str, RegistryEntry],
    *,
    start_index: int = 1,
    end_index: int | None = None,
) -> tuple[list[ManifestRow], set[str]]:
    rows: list[ManifestRow] = []
    covered_sources: set[str] = set()
    dataset_roots = sorted(YOLO_SOURCES_ROOT.iterdir())
    total_datasets = len(dataset_roots)
    for index, dataset_root in enumerate(dataset_roots, start=1):
        if not dataset_root.is_dir() or not (dataset_root / "data.yaml").exists():
            continue
        if index < start_index:
            continue
        if end_index is not None and index > end_index:
            continue
        before_rows = len(rows)
        before_sources = len(covered_sources)
        reg = registry.get(dataset_root.name)
        used_sidecar = False
        for _, _, _, meta_dir in iter_yolo_splits(dataset_root):
            if meta_dir is None:
                continue
            meta_paths = sorted(meta_dir.glob("*.json"))
            if not meta_paths:
                continue
            used_sidecar = True
            total_meta = len(meta_paths)
            for meta_index, meta_path in enumerate(meta_paths, start=1):
                extracted = extract_rows_from_sidecar(meta_path, dataset_root.name, registry)
                if extracted:
                    rows.extend(extracted)
                    for row in extracted:
                        covered_sources.add(row.source)
                if meta_index % 500 == 0 or meta_index == total_meta:
                    log_progress(
                        f"[breed-build] dataset {index}/{total_datasets} {dataset_root.name} "
                        f"metadata_processed={meta_index}/{total_meta} total_rows={len(rows)}"
                    )
        if used_sidecar:
            added_rows = len(rows) - before_rows
            added_sources = len(covered_sources) - before_sources
            if added_rows or added_sources:
                log_progress(
                    f"[breed-build] scanned YOLO dataset {index}/{total_datasets}: {dataset_root.name} "
                    f"added_rows={added_rows} total_rows={len(rows)} covered_sources={len(covered_sources)}"
                )
            continue
        if reg is not None:
            if reg.expected_format not in {"yolo_detection", "createml_detection"} or reg.species_value == "multi":
                continue
            species_id = canonical_species(reg.species_value)
            source_name = reg.dataset_id
            source_type = reg.source_type or "yolo"
            license_name = reg.license
        else:
            guessed_species = guess_species_from_dataset_name(dataset_root.name)
            if guessed_species is None:
                continue
            species_id = guessed_species
            source_name = dataset_root.name
            source_type = "yolo"
            license_name = "unknown"
        extracted = extract_rows_from_plain_yolo(
            dataset_root=dataset_root,
            species_id=species_id,
            source_name=source_name,
            source_type=source_type,
            license_name=license_name,
            progress_prefix=f"[breed-build] dataset {index}/{total_datasets} {dataset_root.name}",
        )
        if extracted:
            rows.extend(extracted)
            covered_sources.add(source_name)
        added_rows = len(rows) - before_rows
        added_sources = len(covered_sources) - before_sources
        if added_rows or added_sources:
            log_progress(
                f"[breed-build] scanned YOLO dataset {index}/{total_datasets}: {dataset_root.name} "
                f"added_rows={added_rows} total_rows={len(rows)} covered_sources={len(covered_sources)}"
            )
    return rows, covered_sources


def detect_boxes_for_raw_images(
    *,
    model_path: Path,
    pending: list[tuple[Path, str, str, str, RegistryEntry]],
    device: str,
    batch_size: int,
    initial_rows: list[ManifestRow] | None = None,
    initial_processed: int = 0,
    initial_matched: int = 0,
    initial_skipped: int = 0,
    progress_callback: Callable[[int, list[ManifestRow], int, int], None] | None = None,
) -> tuple[list[ManifestRow], dict[str, int]]:
    total_pending = initial_processed + len(pending)
    if total_pending == 0:
        return [], {"pending": 0, "matched": 0, "skipped": 0}
    rows: list[ManifestRow] = list(initial_rows or [])
    matched = int(initial_matched)
    skipped = int(initial_skipped)
    if not pending:
        return rows, {"pending": total_pending, "matched": matched, "skipped": skipped}
    model = YOLO(str(model_path))
    log_progress(
        f"[breed-build] detector boxing start pending={total_pending} remaining={len(pending)} "
        f"resume_processed={initial_processed} batch_size={batch_size}"
    )
    for start in range(0, len(pending), batch_size):
        batch = pending[start : start + batch_size]
        valid_items: list[tuple[Path, str, str, str, RegistryEntry]] = []
        for image_path, species_id, breed_id, raw_label, reg in batch:
            if not _is_readable_image(image_path):
                skipped += 1
                log_progress(f"[breed-build] skip unreadable image: {image_path}")
                continue
            valid_items.append((image_path, species_id, breed_id, raw_label, reg))
        result_pairs: list[tuple[tuple[Path, str, str, str, RegistryEntry], Any]] = []
        if valid_items:
            batch_paths = [str(image_path) for image_path, _, _, _, _ in valid_items]
            try:
                results = model.predict(
                    source=batch_paths,
                    verbose=False,
                    device=device,
                    imgsz=1280,
                    conf=0.05,
                    batch=batch_size,
                    stream=False,
                )
                result_pairs = list(zip(valid_items, results, strict=True))
            except Exception as exc:
                log_progress(f"[breed-build] batch predict fallback triggered for {len(valid_items)} images: {exc}")
                for item in valid_items:
                    image_path = item[0]
                    try:
                        single_results = model.predict(
                            source=[str(image_path)],
                            verbose=False,
                            device=device,
                            imgsz=1280,
                            conf=0.05,
                            batch=1,
                            stream=False,
                        )
                        result_pairs.append((item, single_results[0]))
                    except Exception as single_exc:
                        skipped += 1
                        log_progress(f"[breed-build] skip predict-failed image: {image_path} error={single_exc}")
        for (image_path, species_id, breed_id, raw_label, reg), result in result_pairs:
            best = None
            for box in result.boxes:
                cls_idx = int(box.cls.item())
                cls_name = canonical_species(str(result.names.get(cls_idx, "")))
                if cls_name != species_id:
                    continue
                conf = float(box.conf.item())
                xyxy = tuple(float(v) for v in box.xyxy[0].tolist())
                if best is None or conf > best[0]:
                    best = (conf, xyxy)
            if best is None:
                skipped += 1
                continue
            split = _split_for_key(str(image_path.resolve()))
            row = build_row(
                image_path=image_path,
                source=reg.dataset_id,
                source_type=reg.source_type,
                license_name=reg.license,
                species_id=species_id,
                breed_id=breed_id,
                raw_label=raw_label,
                bbox_xyxy=best[1],
                split=split,
                bbox_source="species_detector",
            )
            if row is None:
                skipped += 1
                continue
            rows.append(row)
            matched += 1
        processed = initial_processed + min(start + len(batch), len(pending))
        if processed == total_pending or processed % max(batch_size * 20, 256) == 0:
            log_progress(
                f"[breed-build] detector boxing progress processed={processed}/{total_pending} "
                f"matched={matched} skipped={skipped}"
            )
            if progress_callback is not None:
                progress_callback(processed, rows, matched, skipped)
    return rows, {"pending": total_pending, "matched": matched, "skipped": skipped}


def collect_raw_breed_requests(registry: dict[str, RegistryEntry], covered_sources: set[str]) -> list[tuple[Path, str, str, str, RegistryEntry]]:
    pending: list[tuple[Path, str, str, str, RegistryEntry]] = []
    registry_entries = list(registry.values())
    total_entries = len(registry_entries)
    for index, reg in enumerate(registry_entries, start=1):
        if reg.dataset_id in covered_sources:
            continue
        if reg.expected_format not in {"folder_classification", "species_only_folder"}:
            continue
        if reg.species_value in {"multi", "unknown_species"}:
            continue
        root = locate_dataset_root(reg)
        if root is None:
            continue
        for image_path, breed_label in iter_raw_breed_images(root):
            species_id = canonical_species(reg.species_value)
            breed_slug = canonical_breed_slug(species_id, breed_label, reg.dataset_id)
            if breed_slug == "unknown":
                continue
            pending.append((image_path, species_id, f"{species_id}:{breed_slug}", breed_label, reg))
        if pending:
            log_progress(
                f"[breed-build] scanned raw dataset {index}/{total_entries}: {reg.dataset_id} "
                f"pending_total={len(pending)}"
            )
    return pending


def write_taxonomy(rows: list[ManifestRow], alias_rows: list[dict[str, str]], out_path: Path) -> None:
    species_ids = sorted({row.species_id for row in rows})
    alias_map: dict[str, set[str]] = {}
    for row in alias_rows:
        alias_map.setdefault(row["breed_id"], set()).add(row["raw_label"])
    payload = {
        "version": "temporary_breed_run_v1",
        "description": "Temporary run-scoped taxonomy generated for breed training.",
        "unknown_policy": {
            "species_id": "unknown_species",
            "breed_id": "unknown_breed",
            "allow_unknown_breed_for_training": False,
        },
        "species": [{"id": species_id, "name": species_id.replace("_", " ").title(), "aliases": [species_id]} for species_id in species_ids],
        "breeds": {},
    }
    for species_id in species_ids:
        payload["breeds"][species_id] = []
    for breed_id in sorted({row.breed_id for row in rows}):
        species_id, breed_slug = breed_id.split(":", 1)
        payload["breeds"][species_id].append(
            {
                "id": breed_id,
                "name": breed_slug.replace("_", " ").title(),
                "aliases": sorted({normalize_label(x) for x in alias_map.get(breed_id, set()) if str(x).strip()} | {breed_slug}),
            }
        )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(yaml.safe_dump(payload, sort_keys=False, allow_unicode=False), encoding="utf-8")


def persist_outputs(
    *,
    out_dir: Path,
    final_rows: list[ManifestRow],
    alias_rows: list[dict[str, str]],
    summary: dict[str, Any],
) -> None:
    manifest_csv = out_dir / "manifest.csv"
    manifest_parquet = out_dir / "manifest.parquet"
    taxonomy_yaml = out_dir / "taxonomy.yaml"
    alias_csv = out_dir / "breed_aliases.csv"
    summary_json = out_dir / "summary.json"
    out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.DataFrame([row.__dict__ for row in final_rows])
    if not df.empty:
        df.to_csv(manifest_csv, index=False)
        df.to_parquet(manifest_parquet, index=False)
        pd.DataFrame(alias_rows).to_csv(alias_csv, index=False)
        write_taxonomy(final_rows, alias_rows, taxonomy_yaml)
    summary_json.write_text(json.dumps(summary, indent=2), encoding="utf-8")


def persist_progress_snapshot(
    *,
    out_dir: Path,
    final_rows: list[ManifestRow],
    alias_rows: list[dict[str, str]],
    summary: dict[str, Any],
) -> None:
    persist_outputs(
        out_dir=out_dir / "_progress",
        final_rows=final_rows,
        alias_rows=alias_rows,
        summary=summary,
    )


def load_progress_snapshot(out_dir: Path) -> tuple[list[ManifestRow], dict[str, Any]] | None:
    progress_dir = out_dir / "_progress"
    summary_path = progress_dir / "summary.json"
    manifest_parquet = progress_dir / "manifest.parquet"
    manifest_csv = progress_dir / "manifest.csv"
    if not summary_path.exists():
        return None
    manifest_path = manifest_parquet if manifest_parquet.exists() else manifest_csv
    if not manifest_path.exists():
        return None
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if manifest_path.suffix == ".parquet":
        df = pd.read_parquet(manifest_path)
    else:
        df = pd.read_csv(manifest_path)
    rows = [ManifestRow(**record) for record in df.to_dict(orient="records")]
    return rows, summary


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--species-model", required=True, help="Path to the latest species detector checkpoint.")
    parser.add_argument("--run-name", default="temporary_breed_run")
    parser.add_argument("--device", default="0")
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--yolo-start-index", type=int, default=1)
    parser.add_argument("--yolo-end-index", type=int, default=0, help="0 means no upper bound.")
    parser.add_argument("--save-yolo-only", action="store_true", help="Persist outputs after the YOLO-boxed phase only.")
    parser.add_argument(
        "--checkpoint-every",
        type=int,
        default=640,
        help="Write partial progress outputs every N processed raw images during detector boxing. 0 disables snapshots.",
    )
    parser.add_argument(
        "--resume-from-progress",
        action="store_true",
        help="Resume detector boxing from the run-scoped _progress snapshot if it exists.",
    )
    args = parser.parse_args()

    registry = load_registry()
    log_progress(f"[breed-build] loaded registry entries={len(registry)}")
    yolo_end_index = None if int(args.yolo_end_index) <= 0 else int(args.yolo_end_index)
    yolo_rows, covered_sources = collect_yolo_breed_rows_filtered(
        registry,
        start_index=max(1, int(args.yolo_start_index)),
        end_index=yolo_end_index,
    )
    log_progress(
        f"[breed-build] collected boxed YOLO rows={len(yolo_rows)} covered_sources={len(covered_sources)}"
    )
    if args.save_yolo_only:
        final_rows = sorted(yolo_rows, key=lambda row: (row.split, row.species_id, row.breed_id, row.path))
        alias_rows = [
            {
                "species_id": row.species_id,
                "breed_id": row.breed_id,
                "raw_label": row.raw_label,
                "source": row.source,
            }
            for row in final_rows
        ]
        out_dir = OUT_ROOT / args.run_name
        summary = {
            "run_name": args.run_name,
            "species_model": str(Path(args.species_model).resolve()),
            "dry_run": bool(args.dry_run),
            "yolo_only": True,
            "yolo_start_index": int(args.yolo_start_index),
            "yolo_end_index": yolo_end_index,
            "yolo_box_rows": len(yolo_rows),
            "pending_raw_images": 0,
            "detector_stats": {"pending": 0, "matched": 0, "skipped": 0},
            "final_rows": len(final_rows),
            "species_count": len({row.species_id for row in final_rows}),
            "breed_count": len({row.breed_id for row in final_rows}),
            "output_dir": str(out_dir.resolve()),
            "top_species": pd.Series([row.species_id for row in final_rows]).value_counts().head(20).to_dict() if final_rows else {},
            "top_breeds": pd.Series([row.breed_id for row in final_rows]).value_counts().head(30).to_dict() if final_rows else {},
            "covered_yolo_sources": sorted(covered_sources),
        }
        if not args.dry_run:
            persist_outputs(out_dir=out_dir, final_rows=final_rows, alias_rows=alias_rows, summary=summary)
        print(json.dumps(summary, indent=2))
        return
    pending = collect_raw_breed_requests(registry, covered_sources)
    log_progress(f"[breed-build] collected raw breed requests pending={len(pending)}")

    out_dir = OUT_ROOT / args.run_name
    detector_rows: list[ManifestRow] = []
    detector_stats = {"pending": len(pending), "matched": 0, "skipped": 0}
    resume_processed = 0
    resume_matched = 0
    resume_skipped = 0

    if bool(args.resume_from_progress):
        snapshot = load_progress_snapshot(out_dir)
        if snapshot is not None:
            snapshot_rows, snapshot_summary = snapshot
            detector_rows = [row for row in snapshot_rows if row.bbox_source == "species_detector"]
            snapshot_stats = dict(snapshot_summary.get("detector_stats") or {})
            resume_processed = int(snapshot_stats.get("processed", 0))
            resume_matched = int(snapshot_stats.get("matched", 0))
            resume_skipped = int(snapshot_stats.get("skipped", 0))
            if resume_processed > 0:
                pending = pending[resume_processed:]
                detector_stats = {
                    "pending": int(snapshot_stats.get("pending", len(pending) + resume_processed)),
                    "matched": resume_matched,
                    "skipped": resume_skipped,
                }
                log_progress(
                    f"[breed-build] resumed from _progress processed={resume_processed} "
                    f"matched={resume_matched} skipped={resume_skipped} remaining={len(pending)}"
                )

    def checkpoint_partial(processed: int, partial_detector_rows: list[ManifestRow], matched: int, skipped: int) -> None:
        if int(args.checkpoint_every) <= 0:
            return
        total_pending = detector_stats.get("pending", len(pending) + resume_processed)
        if processed != total_pending and processed % int(args.checkpoint_every) != 0:
            return
        combined_rows = yolo_rows + partial_detector_rows
        dedup_partial: dict[str, ManifestRow] = {row.image_id: row for row in combined_rows}
        final_partial_rows = sorted(
            dedup_partial.values(),
            key=lambda row: (row.split, row.species_id, row.breed_id, row.path),
        )
        alias_partial_rows = [
            {
                "species_id": row.species_id,
                "breed_id": row.breed_id,
                "raw_label": row.raw_label,
                "source": row.source,
            }
            for row in final_partial_rows
        ]
        partial_summary = {
            "run_name": args.run_name,
            "species_model": str(Path(args.species_model).resolve()),
            "dry_run": bool(args.dry_run),
            "partial": True,
            "yolo_box_rows": len(yolo_rows),
            "pending_raw_images": total_pending,
            "detector_stats": {
                "pending": total_pending,
                "processed": processed,
                "matched": matched,
                "skipped": skipped,
            },
            "final_rows": len(final_partial_rows),
            "species_count": len({row.species_id for row in final_partial_rows}),
            "breed_count": len({row.breed_id for row in final_partial_rows}),
            "output_dir": str(out_dir.resolve()),
            "top_species": pd.Series([row.species_id for row in final_partial_rows]).value_counts().head(20).to_dict() if final_partial_rows else {},
            "top_breeds": pd.Series([row.breed_id for row in final_partial_rows]).value_counts().head(30).to_dict() if final_partial_rows else {},
            "covered_yolo_sources": sorted(covered_sources),
        }
        persist_progress_snapshot(
            out_dir=out_dir,
            final_rows=final_partial_rows,
            alias_rows=alias_partial_rows,
            summary=partial_summary,
        )

    if not args.dry_run:
        detector_rows, detector_stats = detect_boxes_for_raw_images(
            model_path=Path(args.species_model),
            pending=pending,
            device=args.device,
            batch_size=max(1, int(args.batch_size)),
            initial_rows=detector_rows,
            initial_processed=resume_processed,
            initial_matched=resume_matched,
            initial_skipped=resume_skipped,
            progress_callback=checkpoint_partial,
        )

    all_rows = yolo_rows + detector_rows
    dedup: dict[str, ManifestRow] = {row.image_id: row for row in all_rows}
    final_rows = sorted(dedup.values(), key=lambda row: (row.split, row.species_id, row.breed_id, row.path))

    alias_rows = []
    for row in final_rows:
        alias_rows.append(
            {
                "species_id": row.species_id,
                "breed_id": row.breed_id,
                "raw_label": row.raw_label,
                "source": row.source,
            }
        )

    summary = {
        "run_name": args.run_name,
        "species_model": str(Path(args.species_model).resolve()),
        "dry_run": bool(args.dry_run),
        "yolo_box_rows": len(yolo_rows),
        "pending_raw_images": len(pending),
        "detector_stats": detector_stats,
        "final_rows": len(final_rows),
        "species_count": len({row.species_id for row in final_rows}),
        "breed_count": len({row.breed_id for row in final_rows}),
        "output_dir": str(out_dir.resolve()),
        "top_species": pd.Series([row.species_id for row in final_rows]).value_counts().head(20).to_dict() if final_rows else {},
        "top_breeds": pd.Series([row.breed_id for row in final_rows]).value_counts().head(30).to_dict() if final_rows else {},
        "covered_yolo_sources": sorted(covered_sources),
    }
    if not args.dry_run:
        persist_outputs(out_dir=out_dir, final_rows=final_rows, alias_rows=alias_rows, summary=summary)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
